  static String normalize(String raw) {
    var t = raw.trim();
    t = t.replaceAll(RegExp(r'[^\u0600-\u06FFa-zA-Z0-9\s\-‌]'), '');
    t = t.replaceAll(RegExp(r'\s+'), ' ').trim();
    return t;
  }

  static String? lookup(String raw) {
    final key = normalize(raw);
    if (key.isEmpty) return null;
    final direct = _entries[key];
    if (direct != null) return direct;
    // Try without ZWNJ / common prefixes.
    final compact = key.replaceAll('‌', '');
    for (final e in _entries.entries) {
      if (e.key.replaceAll('‌', '') == compact) return e.value;
      if (compact.length >= 3 &&
          (e.key.contains(compact) || compact.contains(e.key))) {
        return e.value;
      }
    }
    return null;
  }

  static List<MapEntry<String, String>> suggestions(String raw, {int limit = 8}) {
    final key = normalize(raw).replaceAll('‌', '');
    if (key.isEmpty) {
      return _entries.entries.take(limit).toList();
    }
    final hits = _entries.entries
        .where((e) => e.key.replaceAll('‌', '').contains(key))
        .take(limit)
        .toList();
    return hits;
  }
